CREATE TABLE processo_eiv (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_protocolo       VARCHAR(30)   NOT NULL UNIQUE,
    empreendimento         VARCHAR(150)  NOT NULL,
    requerente             VARCHAR(150)  NOT NULL,
    endereco               VARCHAR(200)  NOT NULL,
    engenheiro_responsavel VARCHAR(150),
    data_protocolo         DATE          NOT NULL,
    prazo_analise_dias     INTEGER       NOT NULL,
    dias_suspensos         INTEGER       NOT NULL DEFAULT 0,
    data_inicio_suspensao  DATE,
    data_vencimento        DATE          NOT NULL,
    status                 VARCHAR(30)   NOT NULL,
    data_conclusao         DATE,
    observacoes            VARCHAR(1000)
);

-- A consulta de alertas filtra por status e ordena pelo vencimento.
CREATE INDEX idx_processo_eiv_status_vencimento ON processo_eiv (status, data_vencimento);
